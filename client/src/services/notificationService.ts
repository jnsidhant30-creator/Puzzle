import { collection, doc, getDocs, updateDoc, deleteDoc, query, where, orderBy, limit, serverTimestamp } from 'firebase/firestore';
import { db } from '../config/firebase';

export type NotificationType = 
  | 'ACHIEVEMENT' 
  | 'LEVEL_UP' 
  | 'DAILY_PUZZLE' 
  | 'PERSONAL_BEST' 
  | 'LEADERBOARD' 
  | 'STREAK' 
  | 'SYSTEM'
  | 'FRIEND_REQUEST'
  | 'FRIEND_ACCEPTED'
  | 'FRIEND_ACTIVITY'
  | 'CHALLENGE_INVITATION'
  | 'CHALLENGE_RESULT'
  | 'DAILY_REWARD'
  | 'BATTLE_CHALLENGE'
  | 'BATTLE_RESULT';

export interface AppNotification {
  id: string;
  userId: string;
  title: string;
  message: string;
  type: NotificationType;
  isRead: boolean;
  metadata?: any;
  createdAt: any;
}

// Memory fallback is removed because all authoritative system notifications are now handled by Cloud Functions.
// Client-created notifications (like Friend Requests) are allowed by security rules when the sender matches auth.uid.

export const markAsRead = async (notificationId: string): Promise<void> => {
  try {
    const docRef = doc(db, 'notifications', notificationId);
    await updateDoc(docRef, { isRead: true });
  } catch (err) {
    console.error("Failed to mark as read:", err);
  }
};

export const markAllAsRead = async (_userId: string, unreadIds: string[]): Promise<void> => {
  for (const id of unreadIds) {
    await markAsRead(id);
  }
};

export const deleteNotification = async (notificationId: string): Promise<void> => {
  try {
    const docRef = doc(db, 'notifications', notificationId);
    await deleteDoc(docRef);
  } catch (err) {
    console.error("Failed to delete notification:", err);
  }
};

export const createNotification = async (
  userId: string,
  title: string,
  message: string,
  type: NotificationType,
  metadata?: any
): Promise<AppNotification> => {
  const newNotif: AppNotification = {
    id: `notif_${Date.now()}_${Math.random().toString(36).substring(2, 9)}`,
    userId,
    title,
    message,
    type,
    isRead: false,
    metadata,
    createdAt: Date.now()
  };

  try {
    const { setDoc } = await import('firebase/firestore');
    const docRef = doc(db, 'notifications', newNotif.id);
    await setDoc(docRef, { ...newNotif, createdAt: serverTimestamp() });
  } catch (err) {
    console.error("Failed to create notification. Note: Authoritative notifications must be generated by Cloud Functions.", err);
  }

  return newNotif;
};
